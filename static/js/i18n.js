class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("surakshaa_lang") || "hi";
  }

  setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) {
      langCode = "hi";
    }
    this.currentLang = langCode;
    localStorage.setItem("surakshaa_lang", langCode);

    // Apply RTL for Urdu or LTR for others
    const langObj = SUPPORTED_LANGUAGES.find(l => l.code === langCode);
    const dir = langObj ? langObj.dir : "ltr";
    document.documentElement.setAttribute("dir", dir);
    document.documentElement.setAttribute("lang", langCode);

    if (dir === "rtl") {
      document.body.classList.add("rtl-mode");
    } else {
      document.body.classList.remove("rtl-mode");
    }

    this.translateDOM();
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS["hi"];
    return dict[key] || TRANSLATIONS["hi"][key] || key;
  }

  translateDOM() {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.setAttribute("placeholder", translation);
        } else {
          el.textContent = translation;
        }
      }
    });

    // Update active state on language selector dropdown / buttons
    document.querySelectorAll(".lang-selector-option").forEach(btn => {
      if (btn.getAttribute("data-lang") === this.currentLang) {
        btn.classList.add("active-lang");
      } else {
        btn.classList.remove("active-lang");
      }
    });
  }
}

const i18n = new I18nManager();
window.i18n = i18n;

